package com.layzen.bdotools.update.domain

/** Запущенная программа и её новые сборки в релизе `desktop-latest`. Ошибки сети и диска — исключения. */
interface UpdateRepository {

    /** Версия запущенной программы; `null`, если она запущена не из пакета и обновлять её нечем. */
    val currentVersion: AppVersion?

    /** Последняя выложенная сборка или `null`, если её описание не прочиталось или не разобралось. */
    suspend fun latest(): UpdateInfo?

    /**
     * Скачивает архив сборки [info], распаковывает его и запускает замену файлов программы: при успехе
     * программа закрывается и запускается снова, поэтому функция не возвращается. [onProgress] получает долю
     * скачанного от 0 до 1. Если в папку программы нельзя писать, сразу бросает исключение.
     */
    suspend fun install(info: UpdateInfo, onProgress: (Float) -> Unit)
}
