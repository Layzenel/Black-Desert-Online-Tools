package com.layzen.bdotools.update.presentation

/** Итог проверки обновлений по кнопке «Проверить обновления»; автоматическая проверка его не меняет. */
enum class UpdateCheckStatus {
    /** Проверку не запускали или её итог уже показан. */
    Idle,

    /** Идёт запрос к GitHub. */
    Checking,

    /** Новее версии нет. */
    UpToDate,

    /** Файл с последней версией не скачался или не разобрался. */
    Failed,
}
