package com.layzen.bdotools.feature.comboassist.domain.combo

/** Куда встаёт ячейка, которую в редакторе бросили на другую. */
enum class DropSide {
    /** Перед ней в той же ветке; у обычной колонки — новой колонкой слева. */
    Before,

    /** После неё в той же ветке; у обычной колонки — новой колонкой справа. */
    After,

    /** Новой веткой развилки над ней. */
    Above,

    /** Новой веткой развилки под ней. */
    Below,
}
