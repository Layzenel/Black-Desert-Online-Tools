package com.layzen.bdotools.feature.comboassist.domain.skill

/** Защита в PvP, которую умение даёт во время использования: на слоте перезарядки она показывается щитом своего цвета. */
enum class SkillProtection {
    /** Устойчивость (Super Armor). */
    SuperArmor,

    /** Защита от атак спереди (Forward Guard). */
    ForwardGuard,

    /** Неуязвимость (Invincible). */
    Invincible,
}
