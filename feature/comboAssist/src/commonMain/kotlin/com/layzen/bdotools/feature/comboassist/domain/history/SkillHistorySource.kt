package com.layzen.bdotools.feature.comboassist.domain.history

import kotlinx.coroutines.flow.Flow

/**
 * Применённые умения из игры: элемент «История испол. навыков» (`UIData Index="158"`) — новая строка снизу,
 * иконка нижней строки сравнивается с иконками умений класса. Читает только экран, в игру не вмешивается.
 * Есть только в настольной версии: в браузере [supported] — `false`, а [watch] ничего не выдаёт.
 */
interface SkillHistorySource {

    /** Может ли платформа следить за игрой. */
    val supported: Boolean

    /**
     * Номера применённых умений по мере появления в истории, пока поток собирают. [icons] — байты иконок
     * умений класса (`SkillNo` → webp/png); незнакомая иконка пропускается. [preferred] — умения комбо и филлеры:
     * среди них иконка ищется сначала, так умения с одинаковой иконкой не путаются с теми, что в комбо.
     */
    fun watch(icons: Map<Int, ByteArray>, preferred: Set<Int>): Flow<Int>

    /**
     * Слоты перезарядок персонажа, которым сейчас играют: он узнаётся по иконкам в слотах на экране, иконки
     * умений даёт [icon]. `null`, если игра не на переднем плане, слотов нет или персонажа не понять.
     */
    suspend fun playedSlots(icon: suspend (Int) -> ByteArray?): List<ScreenSlot>?
}
