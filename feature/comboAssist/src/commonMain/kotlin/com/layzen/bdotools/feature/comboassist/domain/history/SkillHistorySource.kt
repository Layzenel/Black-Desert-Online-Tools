package com.layzen.bdotools.feature.comboassist.domain.history

import com.layzen.bdotools.feature.comboassist.domain.keys.KeyStep
import kotlinx.coroutines.flow.Flow

/**
 * Применённые умения из игры: элемент «История испол. навыков» (`UIData Index="158"`) — новая строка снизу,
 * иконка нижней строки сравнивается с иконками умений класса. Читает только экран, в игру не вмешивается.
 * Есть только в настольной версии: в браузере [supported] — `false`, а [watch] ничего не выдаёт.
 */
interface SkillHistorySource {

    /** Может ли платформа следить за игрой. */
    val supported: Boolean

    /**
     * Какие слоты перезарядок персонажа, последнего узнанного [playedSlots], не видны (номера по порядку его слотов),
     * пока поток собирают: окно умений, настроек или скрытый интерфейс закрывают их целиком или частью. Пока персонаж
     * не узнан — пусто.
     */
    fun hiddenSlots(): Flow<Set<Int>>

    /**
     * Номера применённых умений по мере появления в истории, пока поток собирают. [icons] — байты иконок
     * умений класса (`SkillNo` → webp/png); незнакомая иконка пропускается. [preferred] — умения комбо и филлеры:
     * среди них иконка ищется сначала, так умения с одинаковой иконкой не путаются с теми, что в комбо.
     * [keySteps] — шаги, которых трекер ждёт сейчас: умение, которого игра не пишет в историю ,
     * подтверждается нажатием его клавиш (читаются, но не перехватываются).
     */
    fun watch(icons: Map<Int, ByteArray>, preferred: Set<Int>, keySteps: () -> List<KeyStep>): Flow<Int>

    /**
     * Висят ли в «Списке усилений» (`UIData Index="119"`) три бафа гнева Чёрного духа, пока поток собирают.
     * Пока игра не на переднем плане, значение не меняется.
     */
    fun rageActive(): Flow<Boolean>

    /**
     * Слоты перезарядок персонажа, которым сейчас играют: он узнаётся по иконкам в слотах на экране, иконки
     * умений даёт [icon]. `null`, если игра не на переднем плане, слотов нет или персонажа не понять.
     */
    suspend fun playedSlots(icon: suspend (Int) -> ByteArray?): List<ScreenSlot>?

    /**
     * Видна ли «История испол. навыков» у персонажа, последнего узнанного [playedSlots]: по файлу игры (игра пишет его
     * при смене персонажа, телепорте и выходе, поэтому он отстаёт от игры), а если историю этого персонажа уже
     * прочитали с экрана — видна независимо от файла. Пока персонаж не узнан или следить нельзя — `true`.
     */
    fun historyShown(): Boolean = true
}
