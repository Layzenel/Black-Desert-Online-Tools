package com.layzen.bdotools.feature.uieditor.domain.layout

/**
 * Заглушка надписи под слотом перезарядки: в игре на слот можно повесить текст до [MAX_CHARS] символов,
 * он рисуется под иконкой по центру и может быть шире рамки. Редактор знает только ширину в символах.
 *
 * Размеры в UI-px замерены по скриншоту 2560×1440 при масштабе 0.8 (рамка слота 50 UI-px = 40 px):
 * 20 цифр — 155 px, высота цифр — 8 px, текст начинается на 3 px ниже рамки.
 */
object SlotLabel {
    /** Самая длинная заглушка надписи, символов. */
    const val MAX_CHARS = 20

    /** Ширина заглушки, которую ставит пункт меню. */
    const val DEFAULT_CHARS = 10

    /** Допустимая ширина заглушки надписи, символов. */
    val CHARS_RANGE = 1..MAX_CHARS

    /** Ширина одного символа. shortcut: замер по цифрам, кириллица шире — уточнить по скриншоту с буквами. */
    const val CHAR_WIDTH = 9.7f

    /** Высота заглушки надписи, UI-px: чуть выше букв, чтобы текст надписи в ней читался. */
    const val HEIGHT = 13f

    /** Отступ подложки от текста надписи слева и справа, UI-px. */
    const val TEXT_PADDING = 2f

    /** Промежуток между нижним краем рамки и надписью. */
    const val GAP = 4f

    /** Надпись бывает только у слотов перезарядки. */
    fun allowedFor(id: SlotId): Boolean = id.group == SlotGroup.Cooldown
}
